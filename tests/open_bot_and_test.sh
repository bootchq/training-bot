#!/bin/bash
# Открывает бота в Telegram и запускает интерактивный тест

BOT_USERNAME="training_dag_run_bot"

clear
echo "======================================================================"
echo "🤖 АВТОМАТИЧЕСКОЕ ОТКРЫТИЕ БОТА"
echo "======================================================================"
echo ""

# Открываем бота в Telegram через deep link
echo "🚀 Открываю бота в Telegram..."
open "tg://resolve?domain=$BOT_USERNAME&start=test"

sleep 2

echo "✅ Бот должен открыться в Telegram"
echo ""

# Инструкции
echo "======================================================================"
echo "📋 АВТОМАТИЧЕСКИЙ ТЕСТ - СЛЕДУЙ ИНСТРУКЦИЯМ"
echo "======================================================================"
echo ""
echo "Я буду показывать что нажимать, а ты будешь видеть результат"
echo ""

# Команда 1
echo "┌─────────────────────────────────────────────────────────────────┐"
echo "│ ШАГ 1: Нажми кнопку START в Telegram                           │"
echo "└─────────────────────────────────────────────────────────────────┘"
echo ""
read -p "Нажми Enter когда нажмешь START в Telegram..."

clear
echo "✅ START нажат"
echo ""
echo "Должны появиться 4 inline кнопки:"
echo "   📊 Статистика"
echo "   📅 План"
echo "   🔄 Синхронизация"
echo "   📲 Календарь"
echo ""
read -p "Появились кнопки? (y/n): " has_buttons

if [ "$has_buttons" = "y" ]; then
    echo "✅ PASS: Inline кнопки появились"
else
    echo "❌ FAIL: Inline кнопок нет"
fi

echo ""

# Тест кнопок
echo "┌─────────────────────────────────────────────────────────────────┐"
echo "│ ШАГ 2: Нажми кнопку 📊 Статистика                              │"
echo "└─────────────────────────────────────────────────────────────────┘"
echo ""
read -p "Нажми Enter когда нажмешь кнопку..."

clear
read -p "Кнопка сработала? (y/n): " stats_works
if [ "$stats_works" = "y" ]; then
    echo "✅ PASS: Кнопка Статистика работает"
else
    echo "❌ FAIL: Кнопка Статистика не работает"
fi

echo ""

# Кнопка План
echo "┌─────────────────────────────────────────────────────────────────┐"
echo "│ ШАГ 3: Нажми кнопку 📅 План                                    │"
echo "└─────────────────────────────────────────────────────────────────┘"
echo ""
read -p "Нажми Enter когда нажмешь кнопку..."

clear
read -p "Кнопка сработала? (y/n): " plan_works
if [ "$plan_works" = "y" ]; then
    echo "✅ PASS: Кнопка План работает"
else
    echo "❌ FAIL: Кнопка План не работает"
fi

echo ""

# Кнопка Синхронизация
echo "┌─────────────────────────────────────────────────────────────────┐"
echo "│ ШАГ 4: Нажми кнопку 🔄 Синхронизация                           │"
echo "└─────────────────────────────────────────────────────────────────┘"
echo ""
read -p "Нажми Enter когда нажмешь кнопку..."

clear
read -p "Кнопка сработала? (y/n): " sync_works
if [ "$sync_works" = "y" ]; then
    echo "✅ PASS: Кнопка Синхронизация работает"
else
    echo "❌ FAIL: Кнопка Синхронизация не работает"
fi

echo ""

# Кнопка Календарь - КРИТИЧЕСКИЙ ТЕСТ
echo "┌─────────────────────────────────────────────────────────────────┐"
echo "│ ШАГ 5: Нажми кнопку 📲 Календарь (ВАЖНО!)                      │"
echo "└─────────────────────────────────────────────────────────────────┘"
echo ""
echo "⚠️  Эта кнопка должна отправить ICS файл"
echo "   (НЕ ошибку OAuth!)"
echo ""
read -p "Нажми Enter когда нажмешь кнопку..."

clear
read -p "Бот отправил ICS файл? (y/n): " calendar_works
if [ "$calendar_works" = "y" ]; then
    echo "✅ PASS: Календарь отправил ICS файл!"
    echo "   ✅ Баг с OAuth исправлен!"
else
    echo "❌ FAIL: Календарь не отправил файл"
    read -p "   Что показал бот? (ошибка/ничего): " calendar_error
fi

echo ""

# Команды
echo "┌─────────────────────────────────────────────────────────────────┐"
echo "│ ШАГ 6: Отправь команду /calendar                               │"
echo "└─────────────────────────────────────────────────────────────────┘"
echo ""
read -p "Нажми Enter когда отправишь команду..."

clear
read -p "Команда /calendar отправила ICS файл? (y/n): " cmd_calendar_works
if [ "$cmd_calendar_works" = "y" ]; then
    echo "✅ PASS: Команда /calendar работает"
else
    echo "❌ FAIL: Команда /calendar не работает"
fi

echo ""

# Итоги
clear
echo "======================================================================"
echo "📊 РЕЗУЛЬТАТЫ ТЕСТИРОВАНИЯ"
echo "======================================================================"
echo ""

total=0
passed=0

tests=(
    "$has_buttons:Inline кнопки появились"
    "$stats_works:Кнопка Статистика"
    "$plan_works:Кнопка План"
    "$sync_works:Кнопка Синхронизация"
    "$calendar_works:Кнопка Календарь (ICS файл)"
    "$cmd_calendar_works:Команда /calendar"
)

for test in "${tests[@]}"; do
    result="${test%%:*}"
    name="${test#*:}"
    total=$((total + 1))

    if [ "$result" = "y" ]; then
        echo "✅ PASS | $name"
        passed=$((passed + 1))
    else
        echo "❌ FAIL | $name"
    fi
done

echo ""
echo "======================================================================"
percent=$((passed * 100 / total))
echo "Результат: $passed/$total тестов пройдено ($percent%)"
echo "======================================================================"
echo ""

if [ $percent -eq 100 ]; then
    echo "🎉 ВСЕ ТЕСТЫ ПРОШЛИ!"
elif [ $percent -ge 80 ]; then
    echo "✅ Большинство тестов пройдено"
else
    echo "⚠️  Требуется доработка"
fi

echo ""
