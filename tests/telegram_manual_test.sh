#!/bin/bash
# Простое тестирование через Telegram Desktop без автоматизации

BOT_USERNAME="training_dag_run_bot"
TELEGRAM_APP="/Applications/Telegram 2.app"

clear
echo "======================================================================"
echo "🌐 ТЕСТИРОВАНИЕ БОТА ЧЕРЕЗ TELEGRAM DESKTOP"
echo "======================================================================"
echo "Дата: $(date '+%Y-%m-%d %H:%M:%S')"
echo "Бот: @$BOT_USERNAME"
echo "======================================================================"
echo ""

# Проверка наличия Telegram
if [ ! -d "$TELEGRAM_APP" ]; then
    echo "❌ Telegram Desktop не найден: $TELEGRAM_APP"
    exit 1
fi

# Запускаем Telegram
echo "🚀 Запускаю Telegram Desktop..."
open "$TELEGRAM_APP"
sleep 2

echo "✅ Telegram Desktop запущен"
echo ""

# Инструкции
echo "======================================================================"
echo "📱 КАК ОТКРЫТЬ БОТА"
echo "======================================================================"
echo ""
echo "1. В открывшемся Telegram нажми на поиск (вверху слева)"
echo "2. Введи: @$BOT_USERNAME"
echo "3. Открой чат с ботом"
echo ""
echo "Нажми Enter когда откроешь чат с ботом..."
read

clear
echo "======================================================================"
echo "✅ ЧАТ С БОТОМ ОТКРЫТ"
echo "======================================================================"
echo ""
echo "Теперь протестируй бота по чеклисту ниже"
echo ""

# План тестирования
echo "======================================================================"
echo "📋 ЧЕКЛИСТ ТЕСТИРОВАНИЯ"
echo "======================================================================"
echo ""

echo "┌─────────────────────────────────────────────────────────────────┐"
echo "│ 1. КОМАНДА /start                                               │"
echo "└─────────────────────────────────────────────────────────────────┘"
echo ""
echo "   [ ] Отправь: /start"
echo "   [ ] Должны появиться 4 inline кнопки:"
echo "       • 📊 Статистика"
echo "       • 📅 План"
echo "       • 🔄 Синхронизация"
echo "       • 📲 Календарь"
echo ""

echo "┌─────────────────────────────────────────────────────────────────┐"
echo "│ 2. INLINE КНОПКИ                                                │"
echo "└─────────────────────────────────────────────────────────────────┘"
echo ""
echo "   [ ] Нажми 📊 Статистика"
echo "   [ ] Нажми 📅 План"
echo "   [ ] Нажми 🔄 Синхронизация"
echo "   [ ] Нажми 📲 Календарь → должен отправить ICS файл"
echo ""

echo "┌─────────────────────────────────────────────────────────────────┐"
echo "│ 3. КОМАНДЫ                                                      │"
echo "└─────────────────────────────────────────────────────────────────┘"
echo ""
echo "   [ ] /help → справка"
echo "   [ ] /stats → статистика (или сообщение о Garmin)"
echo "   [ ] /plan → генерация плана тренировок"
echo "   [ ] /calendar → скачивание ICS файла"
echo ""

echo "┌─────────────────────────────────────────────────────────────────┐"
echo "│ 4. ФОРМАТИРОВАНИЕ                                               │"
echo "└─────────────────────────────────────────────────────────────────┘"
echo ""
echo "   [ ] Сообщения отформатированы (жирный текст, списки)"
echo "   [ ] Emoji отображаются"
echo "   [ ] Нет сырых Markdown символов (**, __)"
echo ""

echo "┌─────────────────────────────────────────────────────────────────┐"
echo "│ 5. ПРОВЕРКА ИСПРАВЛЕНИЙ                                         │"
echo "└─────────────────────────────────────────────────────────────────┘"
echo ""
echo "   [ ] /calendar отправляет ICS файл (НЕ ошибку OAuth)"
echo "   [ ] Inline кнопка 📲 Календарь работает"
echo "   [ ] /stats без Garmin показывает понятное сообщение"
echo ""

echo "======================================================================"
echo ""
echo "Нажми Enter когда закончишь тестирование..."
read

clear
echo "======================================================================"
echo "✅ ТЕСТИРОВАНИЕ ЗАВЕРШЕНО"
echo "======================================================================"
echo ""
echo "Telegram Desktop остается открытым"
echo ""
echo "Скриншоты можно сделать через Cmd+Shift+4 в macOS"
echo ""
echo "======================================================================"
echo ""
